export const dictionaries: Record<Language, Dictionary> = { he, en, fr };

export function isLanguage(value: unknown): value is Language {
  return value === "he" || value === "en" || value === "fr";
}

export function translate(language: Language, key: MessageKey, params?: Record<string, string | number>) {
  const template = dictionaries[language][key] ?? he[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}
